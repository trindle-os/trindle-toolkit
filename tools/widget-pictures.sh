#!/bin/sh
# Rebuilds the pictures in docs/images/widgets from the first rust block of each guide in docs/widgets, and the two generated lists that compile and paint them; names may be given to paint only those.
set -eu
cd "$(dirname "$0")/.."

slugs=$(ls docs/widgets/*.md | grep -v README.md | sed 's|docs/widgets/||; s|\.md$||')

{
    echo "// Generated by tools/widget-pictures.sh from docs/widgets/*.md; do not edit."
    echo "macro_rules! guide {"
    echo "    (\$name:ident, \$file:literal) => {"
    echo "        #[doc = include_str!(\$file)]"
    echo "        pub struct \$name;"
    echo "    };"
    echo "}"
    for s in $slugs; do
        echo "guide!(w_$(echo "$s" | tr '-' '_'), \"$s.md\");"
    done
} > docs/widgets/doctests.rs

setting() {
    sed -n "s/^<!-- picture .*$2 \([A-Za-z0-9,]*\).*-->\$/\1/p" "docs/widgets/$1.md" | head -n 1
}

{
    echo "// Generated by tools/widget-pictures.sh from docs/widgets/*.md; do not edit."
    echo "#![allow(dead_code)]"
    echo
    for s in $slugs; do
        echo "pub mod g_$(echo "$s" | tr '-' '_') {"
        awk '
            /^```rust/ && !done { inside = 1; next }
            /^```/ && inside { inside = 0; done = 1; next }
            inside && /^# let _ = view\(\);$/ { next }
            inside { if ($0 == "#") $0 = ""; sub(/^# /, ""); sub(/^fn view\(/, "pub fn view("); sub(/^enum Msg /, "pub enum Msg "); print }
        ' "docs/widgets/$s.md"
        echo "}"
        echo
    done
    echo "pub fn all(only: &[String]) {"
    for s in $slugs; do
        w=$(setting "$s" width)
        h=$(setting "$s" height)
        k=$(setting "$s" keys)
        echo "    crate::snap(only, \"$s\", (${w:-480}, ${h:-0}), \"$k\", g_$(echo "$s" | tr '-' '_')::view);"
    done
    echo "}"
} > examples/widget-pictures/guides.rs

mkdir -p docs/images/widgets
nice cargo +1.85 run --release --example widget-pictures --features ui,testing -- "$@"
[ $# -gt 0 ] || nice cargo +1.85 run --release --example widget-pictures --features ui,testing -- emoji-picker
